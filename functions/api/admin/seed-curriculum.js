const makeId = () => crypto.randomUUID();
export async function onRequestPost(context) {
  const auth = await requireAdmin(context);
  if (auth.response) return auth.response;
  const db = context.env.DB;
  const existing = await db.prepare("SELECT COUNT(*) AS n FROM learning_units WHERE title LIKE 'الفصل %'").first();
  if (Number(existing?.n || 0) > 0) return json({ error:"تمت إضافة هيكل المنهج مسبقاً، لم نكرر البيانات." },409);
  const statements = [];
  let unitCount=0, lessonCount=0;
  for (const term of curriculum) {
    for (let index=0; index<term.chapters.length; index++) {
      const [title, lessonNames] = term.chapters[index];
      const unitId=makeId();
      statements.push(db.prepare("INSERT INTO learning_units (id,title,description,sort_order,published,created_by,semester) VALUES (?,?,?,?,?,?,?)")
        .bind(unitId,title,"منهج الكيمياء للصف الثاني الثانوي · "+(term.semester==="1"?"الفصل الدراسي الأول 2-1":"الفصل الدراسي الثاني 2-2"),index+1,1,auth.user.id,term.semester));
      unitCount++;
      const lessons=lessonNames.split("|");
      for(let j=0;j<lessons.length;j++){
        const lesson=lessons[j], lessonId=makeId();
        const summary="شرح تعليمي لدرس "+lesson+" ضمن "+title+"، يتضمن الفكرة العلمية والمصطلحات والتطبيقات وأسئلة تقويم ذاتي.";
        const body=[
          "منهج الكيمياء للصف الثاني الثانوي",
          title+" — "+lesson,
          "",
          "نواتج التعلم",
          "• أن تشرح الفكرة العلمية المرتبطة بموضوع "+lesson+".",
          "• أن تستخدم المصطلحات والرموز الكيميائية بدقة.",
          "• أن تربط المفهوم بالملاحظة أو النموذج أو الحساب الكيميائي المناسب.",
          "• أن تفسر النتائج وتبرر إجابتك باستخدام دليل علمي.",
          "",
          "تمهيد وفهم الفكرة",
          "يركز هذا الدرس على "+lesson+" بوصفه جزءاً من "+title+". لفهم الموضوع ابدأ بتحديد ما الذي تصفه الفكرة الكيميائية، وما الجسيمات أو المواد أو الطاقة التي تتأثر بها، ثم اربط ذلك بما درسته سابقاً عن تركيب المادة وسلوكها.",
          "",
          "طريقة دراسة المفهوم",
          "1. اقرأ عنوان الدرس وحدد المصطلحات العلمية الجديدة.",
          "2. اكتب تعريفاً دقيقاً لكل مصطلح بلغتك، مع المحافظة على المعنى العلمي.",
          "3. ارسم نموذجاً أو مخططاً يوضح العلاقة بين عناصر الفكرة عند الحاجة.",
          "4. إذا تضمن الدرس قانوناً أو علاقة رياضية، فاكتب الرموز والوحدات وحدد متى تستخدم العلاقة.",
          "5. حل مثالاً خطوة بخطوة، ثم أعد حله دون النظر إلى الحل.",
          "",
          "تطبيق ومهارة علمية",
          "عند حل أي سؤال في "+lesson+" اتبع هذا التسلسل: حدد المعطيات والمطلوب، اختر المفهوم أو القانون المناسب، اكتب خطوات الاستدلال بوضوح، ثم تحقق من منطق النتيجة ووحداتها إن وجدت. لا تكتفِ بحفظ الإجابة؛ اشرح لماذا هي صحيحة.",
          "",
          "تحقق من فهمك",
          "1. ما الفكرة الرئيسة التي يشرحها درس "+lesson+"؟",
          "2. اذكر مصطلحين علميين يرتبطان بالدرس واشرحهما.",
          "3. كيف يمكن تطبيق المفهوم على مثال من الحياة أو من مسائل الكيمياء؟",
          "4. ما الخطأ الشائع الذي ينبغي الانتباه إليه عند حل أسئلة هذا الموضوع؟",
          "",
          "ملخص المراجعة",
          "• افهم المفهوم قبل حفظ المصطلحات.",
          "• اربط الشرح بالنماذج والرموز والمعادلات ذات الصلة.",
          "• تدرب على أسئلة متنوعة وراجع سبب صحة كل إجابة.",
          "",
          "ملاحظة تعليمية: هذا شرح دراسي منظم للمراجعة وبناء الفهم، ويُستخدم مع كتاب الطالب وشرح المعلم؛ ولا يُعد بديلاً عن النص الرسمي للكتاب أو تعليمات المعلم."
        ].join("\n");
        statements.push(db.prepare("INSERT INTO lessons (id,unit_id,title,summary,content,sort_order,published,created_by) VALUES (?,?,?,?,?,?,?,?)")
          .bind(lessonId,unitId,lesson,summary,body,j+1,1,auth.user.id));
        lessonCount++;
      }
    }
  }
  await db.batch(statements);
  return json({ok:true,units:unitCount,lessons:lessonCount,message:"تم تجهيز هيكل الفصلين الدراسيين."},201);
}
